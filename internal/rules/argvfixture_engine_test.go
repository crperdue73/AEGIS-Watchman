// argvfixture_engine_test.go — the 100 argvfixture rows, judged by the COMPILED engine.
//
// Third and last glob-bearing family. Beat 777 bridged path (77 rows), beat 778 bridged endpoint
// (33 rows). `argv_any` was the one left, and it is the one that decides whether a command line
// looks like an install pipe, a persistence trick, an obfuscation, a privileged container, or a
// reverse shell — 7 of the pack's 20 rules.
//
// THE JOINING PROBLEM, and why this bridge is not shaped like the other two.
// `scripts/argvfixture.py` judges rows with `packcheck.match_one(glob, cmd, ...)` — it hands the
// matcher a COMMAND STRING. The engine does not work that way: auditd hands back an argv LIST, and
// `anyArgvMatches` (engine.go:212) tests every element, then the exe, then `strings.Join(argv, " ")`.
// So the probe tests one string, and the engine tests a *derived* one. Beat 650 found this and
// proved that phrase globs like `*pip install*` are matched ONLY by the joined line.
//
// That makes transcription the whole risk: if I re-type the command strings and split them myself,
// I am building the joined line by hand and then certifying the step that builds it. So the rows
// come from the probe by generator, and the SPLIT is measured rather than assumed:
//
//	TestArgvSplitLosesQuoting declares that 10 rows do not survive shlex+space-join unchanged,
//	and fails if that number moves in either direction. Those 10 are rows where the probe's verdict
//	is about a DIFFERENT STRING than the engine can ever produce — `echo 'x' >> ~/.bashrc` judges
//	the quoted line, but the engine sees `echo x >> ~/.bashrc`. If a future row starts depending on
//	quoting that disappears on the join, this test is what says so out loud.
//
// WHAT A GREEN HERE MEANS: the Python mirror's verdicts are correct for these 100 rows, and — for
// the 90 whose join is identity — the probe was asking about the same string the engine sees. It
// does NOT mean the argv family is in good shape: one row is a declared FALSE NEGATIVE (`*|sh*`
// does not fire on `| bash`, so the identical attack spelled in bash walks through), and nine are
// declared LOOKALIKE over-matches. Those are pinned, not fixed — pack changes are Dad's call.
//
// BEAT 779 — table generated by `scripts/pathtable.py --family argv`, for the reason recorded in
// beats 777 and 778: my hand copy of the path table was wrong three ways and the bad red was
// indistinguishable from a real finding.

