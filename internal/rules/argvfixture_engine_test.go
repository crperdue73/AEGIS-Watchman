// argvRow is one row of the probe's ROWS table: (glob, command, want, category).
type argvRow struct {
	glob string
	cmd  string
	want bool
	// category is the probe's own label: SELF, CLEAN, LOOKALIKE, or FALSE NEGATIVE.
	category string
}

// argvFire reproduces the probe's judgement exactly: `shlex.split(cmd)` into an argv list, then
// the engine's own `anyArgvMatches`. No `exe` is supplied because the probe supplies none — adding
// one would test a question the probe never asked and make the two verdicts incomparable.
func argvFire(t *testing.T, glob, cmd string) bool {
	t.Helper()
	e := argvPack(t, `["`+glob+`"]`)
	argv := shlexSplit(t, cmd)
	return fire(e, argv[0], argv...)
}

// shlexSplit is a transcription of Python's `shlex.split` with default settings — the exact call
// `scripts/argvfixture.py` makes. It is a MIRROR, not a reference: there is no shlex in Go, so the
// probe's parser had to be ported to run the same rows here. What that means for this file:
//
//   - The bridge asks the compiled engine about the argv list this function produces, so the
//     ENGINE verdict is real. What is transcribed is only how a readable command string becomes a
//     list, and that step is identical on both sides only if this port is faithful.
//   - TestShlexSplitMatchesPythonDeclared proves faithfulness on the 100 rows in the table, which
//     is the only reason the comparison is meaningful. It pins the expected argv for every row.
//
// Rules implemented: single/double quotes group and are removed, backslash escapes outside single
// quotes, `#` is NOT a comment character mid-line (that is shlex's behaviour and beat 652's whole
// finding — a comment-looking argument IS an argument).
//
// MEASURED LIMIT of TestShlexSplitParity (beat 779, mutation M1): NO row in the table contains a
// backslash, so the escape branches have zero coverage. Deleting them leaves the parity test green
// — I tried it and counted 0 failures. They are kept because shlex has them and a future row may
// use one, but this is an unexercised branch and the comment says so rather than letting a green
// parity test imply otherwise. Same shape as beat 646's untested CRASH branch.
func shlexSplit(t *testing.T, s string) []string {
	t.Helper()
	var (
		out                           []string
		cur                           strings.Builder
		inSingle, inDouble, haveToken bool
	)
	flush := func() {
		if haveToken {
			out = append(out, cur.String())
			cur.Reset()
			haveToken = false
		}
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case inSingle:
			if c == '\'' {
				inSingle = false
			} else {
				cur.WriteByte(c)
			}
		case inDouble:
			if c == '"' {
				inDouble = false
			} else if c == '\\' && i+1 < len(s) {
				i++
				cur.WriteByte(s[i])
			} else {
				cur.WriteByte(c)
			}
			haveToken = true
		case c == '\'':
			inSingle = true
			haveToken = true
		case c == '"':
			inDouble = true
			haveToken = true
		case c == ' ' || c == '\t' || c == '\n' || c == '\r':
			flush()
		case c == '\\' && i+1 < len(s):
			i++
			cur.WriteByte(s[i])
			haveToken = true
		default:
			cur.WriteByte(c)
			haveToken = true
		}
	}
	if inSingle || inDouble {
		t.Fatalf("shlexSplit: unbalanced quote in %q", s)
	}
	flush()
	return out
}

// TestShlexSplitEscapeBranches exercises the part of shlexSplit the parity fixture cannot reach.
// Mutation M1 deleted the backslash-escape branch and TestShlexSplitParity stayed green, because
// none of the 100 rows contains a backslash. So the branch gets its own cases here — not from the
// probe, but from Python's documented behaviour, which is the reference the port claims to match.
func TestShlexSplitEscapeBranches(t *testing.T) {
	cases := []struct {
		in   string
		want []string
	}{
		{`a\ b`, []string{"a b"}},                 // escaped space does not split
		{`echo "a\"b"`, []string{"echo", "a\"b"}}, // escape inside double quotes
		{`x \# y`, []string{"x", "#", "y"}},       // escaped # is a literal, not a comment
		{`'a\b'`, []string{`a\b`}},                // single quotes: backslash is literal
	}
	for _, c := range cases {
		got := shlexSplit(t, c.in)
		if len(got) != len(c.want) {
			t.Errorf("shlexSplit(%q) = %q, want %q", c.in, got, c.want)
			continue
		}
		for i := range got {
			if got[i] != c.want[i] {
				t.Errorf("shlexSplit(%q)[%d] = %q, want %q (full %q vs %q)",
					c.in, i, got[i], c.want[i], got, c.want)
				break
			}
		}
	}
}

// TestArgvFixtureAgreesWithCompiledEngine is the bridge over all 100 rows.
func TestArgvFixtureAgreesWithCompiledEngine(t *testing.T) {
	if len(argvRows) != argvRowCount {
		t.Fatalf("argvRows has %d rows, generator says %d — the table was edited by hand",
			len(argvRows), argvRowCount)
	}
	var diffs int
	for _, r := range argvRows {
		got := argvFire(t, r.glob, r.cmd)
		if got == r.want {
			continue
		}
		// The one declared false negative is allowed to be wrong in the safe direction ONLY
		// as a recorded gap. Any other disagreement is a mirror that lied.
		if r.category == "FALSE NEGATIVE" && got == false {
			continue
		}
		diffs++
		t.Errorf("MIRROR/ENGINE DISAGREE glob=%q cmd=%q [%s]: python said want=%v, Go says %v",
			r.glob, r.cmd, r.category, r.want, got)
	}
	if diffs > 0 {
		t.Errorf("%d disagreements — the Python mirror is not a faithful oracle for these rows", diffs)
	}
}

// TestArgvDeclaredFalseNegativeStillWalkthrough pins the gap rather than hiding it. `*|sh*` catches
// a pipe into sh; the same attack spelled `| bash` is not caught. When the pack learns bash/zsh/
// python, this goes red and says the gap closed. Until then it is a named defect with a test on it,
// which is the difference between an accepted risk and an accident nobody noticed.
func TestArgvDeclaredFalseNegativeStillWalkthrough(t *testing.T) {
	var n int
	for _, r := range argvRows {
		if r.category != "FALSE NEGATIVE" {
			continue
		}
		n++
		if argvFire(t, r.glob, r.cmd) {
			t.Errorf("declared FALSE NEGATIVE now FIRES: glob=%q cmd=%q — the pack may have "+
				"learned other shells. Promote this row in scripts/argvfixture.py and regenerate.",
				r.glob, r.cmd)
		}
	}
	if n != 1 {
		t.Errorf("found %d declared FALSE NEGATIVE rows, expected 1 — the census drifted", n)
	}
}

// TestArgvSplitLosesQuoting is the honesty test for this family. The probe judges a shell-quoted
// string; auditd hands the engine an argv list, and the engine's joined candidate is a single-space
// re-join of that list. For 10 of 100 rows those are not the same string, so the probe's verdict is
// not literally the engine's question. That is measured and pinned — a change in either direction
// means rows moved between "the probe asked exactly the engine's question" and "it didn't".
func TestArgvSplitLosesQuoting(t *testing.T) {
	var lossy int
	for _, r := range argvRows {
		argv := shlexSplit(t, r.cmd)
		if strings.Join(argv, " ") != r.cmd {
			lossy++
		}
	}
	const declared = 10
	if lossy != declared {
		t.Errorf("%d rows lose quoting on the argv join, declared %d — the probe's question "+
			"drifted from the engine's question. Re-measure and update the declaration with a "+
			"reason, do not just bump the number.", lossy, declared)
	}
}

// TestShlexSplitParity measures the splitter against Python's own output. The expected argv for
// every row is generated by `scripts/shlexparity.py` FROM `shlex.split` — so this is not a test of
// my port against my reading of my port, it is the port against the reference implementation.
//
// Without this, every other assertion in this file rests on a transcription nobody checked, and a
// mirror checking a mirror (beat 642).
func TestShlexSplitParity(t *testing.T) {
	raw, err := os.ReadFile("testdata/shlexparity.json")
	if err != nil {
		t.Fatalf("cannot read shlex parity fixture (run `python3 scripts/shlexparity.py`): %v", err)
	}
	var doc struct {
		Cases []struct {
			Cmd  string   `json:"cmd"`
			Argv []string `json:"argv"`
		} `json:"cases"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("shlex parity fixture is not valid JSON: %v", err)
	}
	if len(doc.Cases) != argvRowCount {
		t.Errorf("parity fixture has %d cases, argv table has %d rows — regenerate with "+
			"`python3 scripts/shlexparity.py`", len(doc.Cases), argvRowCount)
	}
	for _, c := range doc.Cases {
		got := shlexSplit(t, c.Cmd)
		if len(got) != len(c.Argv) {
			t.Errorf("SPLIT PARITY cmd=%q: python gave %d elements %q, go gave %d %q",
				c.Cmd, len(c.Argv), c.Argv, len(got), got)
			continue
		}
		for i := range got {
			if got[i] != c.Argv[i] {
				t.Errorf("SPLIT PARITY cmd=%q element %d: python %q, go %q (full: python %q, go %q)",
					c.Cmd, i, c.Argv[i], got[i], c.Argv, got)
				break
			}
		}
	}
}

