// endpointRow is one row of the probe's FIXTURES table: (glob, endpoint, want).
type endpointRow struct {
	glob      string
	endpoint  string
	want      bool
	lookalike bool // declared false-positive tolerance: someone else's domain, expected to fire
}

// endpointFire builds a single-rule engine whose only predicate is endpoint_glob_any on a
// net.egress action, and reports whether the endpoint fires it.
func endpointFire(t *testing.T, glob, endpoint string) bool {
	t.Helper()
	p := mustPack(t, `
name: endpoint-semantics
rules:
  - id: endpoint.semantics.probe
    severity: high
    match:
      type: net.egress
      endpoint_glob_any: ["`+glob+`"]
`)
	e := NewEngine(p)
	evs := e.Match(
		schema.Host{ID: "h1"}, nil,
		schema.Action{Type: "net.egress", Detail: map[string]any{"endpoint": endpoint}},
		nil, timeNow(),
	)
	return len(evs) > 0
}

// TestEndpointFixtureAgreesWithCompiledEngine is the bridge. Counts come from the generator, so
// a truncated table cannot pass silently.
func TestEndpointFixtureAgreesWithCompiledEngine(t *testing.T) {
	if len(endpointRows) != endpointRowCount {
		t.Fatalf("endpointRows has %d rows, generator says %d — the table was edited by hand",
			len(endpointRows), endpointRowCount)
	}
	var diffs int
	for _, r := range endpointRows {
		got := endpointFire(t, r.glob, r.endpoint)
		if got == r.want {
			continue
		}
		diffs++
		t.Errorf("MIRROR/ENGINE DISAGREE glob=%q endpoint=%q: python said want=%v, Go says %v",
			r.glob, r.endpoint, r.want, got)
	}
	if diffs > 0 {
		t.Errorf("%d disagreements — the Python mirror is not a faithful oracle for these rows",
			diffs)
	}
}

// TestEndpointLookalikesStillFire pins the declared false-positive tolerance. Every one of these
// endpoints belongs to someone else and is expected to fire anyway, because `*x*` cannot say "x
// is a domain label". If a host-aware matcher ever lands, these go red — telling us to promote
// them to False rather than leaving a silent over-match in a high-severity exfil rule.
func TestEndpointLookalikesStillFire(t *testing.T) {
	var fired, total int
	for _, r := range endpointRows {
		if !r.lookalike {
			continue
		}
		total++
		if endpointFire(t, r.glob, r.endpoint) {
			fired++
		}
	}
	if total != 9 {
		t.Errorf("declared lookalike rows: %d, expected 9 — the probe's LOOKALIKE census drifted", total)
	}
	if fired != total {
		t.Errorf("%d of %d declared lookalikes stopped firing and %d still do — a host-aware "+
			"matcher may have landed. Promote the quiet ones in scripts/endpointfixture.py and "+
			"regenerate this table.", total-fired, total, fired)
	}
}

